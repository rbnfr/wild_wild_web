import {
  mkdtemp,
  readdir,
  readFile,
  unlink,
  rmdir,
  lstat,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const target = "refs/heads/hostinger-static";
const marker = "Generated-Static-Deployment: v1";
function git(args, options = {}) {
  const result = spawnSync("git", args, {
    cwd: root,
    encoding: "utf8",
    ...options,
  });
  if (result.status !== 0)
    throw new Error(result.stderr || `Git failed: ${args[0]}`);
  return result.stdout.trim();
}
if (git(["branch", "--show-current"]) !== "static-version")
  throw new Error("Run this from the source branch static-version.");
git(["diff", "--quiet", "HEAD", "--"]);
if (git(["ls-files", "--others", "--exclude-standard"]))
  throw new Error(
    "Commit the source changes before generating the deployment branch.",
  );
const source = git(["rev-parse", "HEAD"]);
const previousResult = spawnSync("git", ["rev-parse", "--verify", target], {
  cwd: root,
  encoding: "utf8",
});
const localPrevious =
  previousResult.status === 0 ? previousResult.stdout.trim() : undefined;
// Fresh CI clones have the remote-tracking ref but no local hosting branch.
const remotePreviousResult = spawnSync(
  "git",
  ["rev-parse", "--verify", "refs/remotes/origin/hostinger-static"],
  { cwd: root, encoding: "utf8" },
);
const previous =
  localPrevious ||
  (remotePreviousResult.status === 0
    ? remotePreviousResult.stdout.trim()
    : undefined);
if (previous && !git(["log", "-1", "--format=%B", previous]).includes(marker))
  throw new Error(
    "hostinger-static already exists and was not generated by this script.",
  );
// Never change a branch that is checked out in any worktree.
if (
  git(["worktree", "list", "--porcelain"])
    .split("\n")
    .includes(`branch ${target}`)
)
  throw new Error(
    "Switch the hostinger-static worktree to another branch first.",
  );

const files = new Map();
const output = resolve(root, "out");
if ((await lstat(output)).isSymbolicLink())
  throw new Error("The export directory must not be a symbolic link.");
async function collect(directory, prefix = "") {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const name = prefix + entry.name;
    if (
      /(^|\/)(?:\.env[^/]*|\.git|node_modules|src|docs|\.docs|CVs|api)(?:\/|$)/i.test(
        name,
      )
    )
      throw new Error(`Source or private file in export: ${name}`);
    if (entry.isDirectory())
      await collect(join(directory, entry.name), `${name}/`);
    else if (entry.isFile())
      files.set(name, await readFile(join(directory, entry.name)));
    else throw new Error(`Unexpected filesystem entry: ${name}`);
  }
}
await collect(output);
for (const name of [
  "index.html",
  ".htaccess",
  "404.html",
  "privacidad/index.html",
  "aviso-legal/index.html",
  "cookies/index.html",
  "robots.txt",
  "sitemap.xml",
])
  if (!files.has(name)) throw new Error(`Missing deployment file: ${name}`);
if (!files.get("index.html").toString().includes("Mary"))
  throw new Error("The exported index is not the Mary Granero website.");

// A separate index leaves the checkout, its staging area and source history intact.
const temporary = await mkdtemp(join(tmpdir(), "mary-static-git-"));
const env = { ...process.env, GIT_INDEX_FILE: join(temporary, "index") };
try {
  git(["read-tree", "--empty"], { env });
  for (const [name, bytes] of [...files].sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const blob = git(["hash-object", "-w", "--stdin"], { input: bytes });
    // All exported files are readable, non-executable Git files (100644).
    git(["update-index", "--add", "--cacheinfo", `100644,${blob},${name}`], {
      env,
    });
  }
  const tree = git(["write-tree"], { env });
  if (
    previous &&
    git(["rev-parse", `${previous}^{tree}`]) === tree &&
    git(["log", "-1", "--format=%B", previous]).includes(
      `Source-Commit: ${source}`,
    )
  ) {
    console.log("hostinger-static already contains this export.");
  } else {
    const commit = git(
      ["commit-tree", tree, ...(previous ? ["-p", previous] : [])],
      {
        input: `Publish static Mary Granero website\n\n${marker}\nSource-Commit: ${source}\n`,
      },
    );
    // Compare-and-swap avoids overwriting a concurrent branch update.
    git([
      "update-ref",
      target,
      commit,
      localPrevious || "0".repeat(source.length),
    ]);
    console.log(
      `hostinger-static prepared: ${files.size} files, commit ${commit.slice(0, 7)}.`,
    );
  }
  console.log("No remote changed. Push with: git push origin hostinger-static");
} finally {
  // Delete only the named files in the newly created temporary directory.
  for (const name of ["index", "index.lock"])
    await unlink(join(temporary, name)).catch((error) => {
      if (error.code !== "ENOENT") throw error;
    });
  await rmdir(temporary);
}
